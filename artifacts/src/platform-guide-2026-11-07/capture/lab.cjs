const fs = require('node:fs');
let stage = 'initial', pairingSecret = '';
const c = require('./common.cjs');
(async () => {
  const token = process.env.LAB_TEST_PAIRING_TOKEN_FILE ? fs.readFileSync(process.env.LAB_TEST_PAIRING_TOKEN_FILE,'utf8').trim() : process.env.LAB_TEST_PAIRING_TOKEN;
  if (!token) throw new Error('FRESH_ONE_USE_PAIRING_TOKEN_REQUIRED');
  pairingSecret = token;
  const manifest = [], browser = await c.launch();
  try {
    const page = await browser.newPage({ viewport:{width:1440,height:960}, deviceScaleFactor:1 });
    page.setDefaultTimeout(60000);
    stage='open Twin'; await page.goto('http://127.0.0.1:4175/#twin');
    await page.getByRole('button',{name:'EN',exact:true}).click();
    const health = await (await page.request.get('http://127.0.0.1:4175/lab/v2/health')).json();
    c.expect(health.sourceCommit).toBe(c.runtimePin.sourceCommit);
    c.expect(health.schemaHash).toBe(c.runtimePin.schemaHash);
    c.expect(health.capabilities).toContain('engineering_bundle_v1');
    await page.locator('#twin-pair-token').fill(token);
    const paired = page.waitForResponse(r=>r.url().endsWith('/lab/v2/sessions')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Pair runtime',exact:true}).click();
    c.expect((await paired).status()).toBe(201);
    await c.expect(page.locator('#twin-pair-token')).toHaveCount(0);
    const shot = (id,title,scope,locator,environment='local-fixture') => c.capture(page,manifest,{id,title,repo:'lab',environment,scope,locator,runtimePin:['lab-compiler-preview','lab-compiler-scene','lab-twin','lab-results','lab-results-panel'].includes(id)?c.runtimePin.sourceCommit:null});
    await page.goto('http://127.0.0.1:4175/#assembly');
    await c.expect(page.getByTestId('assembly-page')).toBeVisible();
    await page.getByRole('button',{name:'Open FD01 reference AMR',exact:true}).click();
    await c.expect(page.getByTestId('asm-instances').locator('tr')).toHaveCount(7);
    await c.expect(page.getByTestId('asm-save-state')).toHaveAttribute('data-state','saved');
    await c.expect(page.getByTestId('asm-est-mass')).toContainText('kg');
    await c.expect(page.getByTestId('asm-est-energy')).toContainText('unknown');
    await shot('lab-assembly','Lab: lắp ráp AMR tham chiếu','Local FD01 reference engineering project; structural design preview, saved in fresh browser context; no native or physical validation.');
    await shot('lab-estimates','Lab: ước tính khối lượng và năng lượng','Engineering estimates panel from FD01 reference; nominal mass only, unknown energy with missing-input reason; no battery duty or hardware qualification.',page.getByTestId('asm-estimates'));
    const compiled = page.waitForResponse(r=>r.url().endsWith('/lab/v2/engineering/compile')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Compile on runtime',exact:true}).click();
    const response = await compiled;
    c.expect(response.ok()).toBe(true);
    const receipt = await response.json();
    c.expect(receipt.state).toBe('compiled');
    await c.expect(page.getByTestId('asm-receipt')).toHaveAttribute('data-state','compiled');
    await c.expect(page.getByTestId('asm-scene').locator('canvas,svg').first()).toBeVisible();
    await shot('lab-compiler-preview','Lab: kết quả compiler và cảnh sinh ra','Actual localhost pinned runtime engineering compile receipt and compiler-generated scene; compiler preview only, no native physics execution or hardware validation.',undefined,'local-compiler-preview');
    await shot('lab-compiler-scene','Lab: cảnh AMR từ compiler','Compiler-generated geometry of FD01 AMR; actual local compiled scene, no native simulation.',page.getByTestId('asm-scene'),'local-compiler-preview');
    stage='open Twin'; await page.goto('http://127.0.0.1:4175/#twin');
    await c.expect(page.locator('#twin-pair-token')).toHaveCount(0);
    stage='coffee preset'; await page.locator('[data-action="twin-preset"][data-value="coffee"]').click();
    stage='create mock run'; await page.getByRole('button',{name:'Run mock',exact:true}).click();
    stage='mock badge'; await c.expect(page.getByTestId('mode-badge')).toContainText('MOCK');
    stage='run identity'; await c.expect(page.getByTestId('run-identity')).toContainText(c.runtimePin.sourceCommit.slice(0,7));
    stage='2D view'; await page.getByRole('button',{name:'2D',exact:true}).click();
    await c.expect(page.getByTestId('twin-scene').locator('svg')).toHaveCount(1);
    await shot('lab-twin','Lab: Twin đang chạy mock','Real pinned local runtime session using BV01 coffee MOCK backend; modeled kinematic visualization and synthetic devices, no native physics evidence.');
    stage='speed'; await page.locator('#twin-run-speed').selectOption('64');
    await page.locator('[data-action="twin-play"]').click();
    await c.expect(page.getByTestId('run-status')).toContainText('Completed',{timeout:180000});
    await c.expect(page.getByTestId('run-served')).toContainText('2');
    await c.expect(page.getByTestId('report-panel')).toBeVisible();
    await shot('lab-results','Lab: kết quả và báo cáo mock','Completed BV01 MOCK run through actual pinned local runtime; 2 served synthetic coffee orders; no native execution or hardware evidence.');
    await shot('lab-results-panel','Lab: báo cáo lần chạy','Report panel of completed local MOCK BV01 run; journal/telemetry and export actions; no native evidence claim.',page.getByTestId('report-panel'));
  } finally { await browser.close(); c.saveManifest('lab',manifest); }
})().catch(error => { console.error('Lab capture failed at '+stage+'; '+(pairingSecret ? String(error.message).replaceAll(pairingSecret,'<redacted>') : String(error.message)).split('\n').slice(0,5).join(' ').slice(0,450)); process.exitCode=1; });
