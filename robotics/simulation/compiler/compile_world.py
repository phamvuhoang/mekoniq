"""compile_world(project_json, asset_revisions, output_dir) -> manifest. One validated model renders every output (SDF, map, bindings, URDF, Nav2 overlay,
scene index); nothing is written before the whole bundle rendered. Identity = canonical hash of {project, assets}; no timestamps anywhere."""
import json
import math

from worlds.generate_restaurant import box_sdf, mover_sdf

from actors.blocker import PARK, BlockerSchedule
from actors.scenario import actor_schedules

from .manifest import canonical_hash, resolve_output, write_hashed_bundle
from .models import WALL_HEIGHT_M, CompileError, WorldModel, quat_to_rpy
from .occupancy import RESOLUTION_M, map_identity, map_yaml, occupancy_pgm

DEFAULT_MAX_LINEAR_MPS, WHEEL_WIDTH_M, CASTER_INSET_M = 0.6, 0.05, 0.1
DEFAULT_WHEEL = {"separationM": 0.42, "radiusM": 0.10}


def num(v):
    s = f"{v:.6f}".rstrip("0").rstrip(".")
    return s if s not in ("", "-", "-0") else "0"


def origin(position, quaternion):
    r, p, y = quat_to_rpy(quaternion)
    return f'<origin xyz="{num(position[0])} {num(position[1])} {num(position[2])}" rpy="{num(r)} {num(p)} {num(y)}"/>'


def geometry_xml(shape):
    if shape.kind == "box":
        return '<box size="%s"/>' % " ".join(num(v) for v in shape.dims["sizeM"])
    if shape.kind == "cylinder":
        return f'<cylinder radius="{num(shape.dims["radiusM"])}" length="{num(shape.dims["heightM"])}"/>'
    return f'<sphere radius="{num(shape.dims["radiusM"])}"/>'


def world_sdf(model, actors=(), blockers=None, beverage=None):
    w, H = model.world, model.fixture_height_m
    boxes = [box_sdf(f"wall_{i}", x + bw / 2, y + bh / 2, bw, bh, WALL_HEIGHT_M) for i, (x, y, bw, bh) in enumerate(model.walls)]
    boxes += [box_sdf(f"fixture_{o['id']}", o["x"] + o["width"] / 2, o["y"] + o["height"] / 2, o["width"], o["height"], H) for o in w["obstacles"]]
    # scripted actors spawn at their first waypoint (the worker drives them from start_tick); blockers wait parked outside the world
    boxes += [mover_sdf(a.model, a.trajectory.waypoints[0][0], a.trajectory.waypoints[0][1], 2 * a.radius_m, a.height_m, "0.9 0.3 0.1 1") for a in actors]
    boxes += [mover_sdf(BlockerSchedule.model(b), PARK[0], PARK[1], (b["width"], b["height"]), b["heightM"], "0.6 0.1 0.6 1") for b in (blockers.blockers if blockers else [])]
    for c in (beverage or {}).get("cups", []):
        xyz = " ".join(num(v) for v in c["positionM"])
        # Pose-driven SIM cup; collision geometry remains present. No physical grasp/force claim.
        boxes.append(f'''<model name="{c['gazeboModel']}"><pose>{xyz} 0 0 0</pose><static>false</static><link name="cup"><gravity>false</gravity><kinematic>true</kinematic><inertial><mass>0.1</mass><inertia><ixx>0.0001</ixx><iyy>0.0001</iyy><izz>0.0001</izz></inertia></inertial><collision name="cup_collision"><geometry><cylinder><radius>0.035</radius><length>0.09</length></cylinder></geometry></collision><visual name="cup_visual"><geometry><cylinder><radius>0.035</radius><length>0.09</length></cylinder></geometry></visual></link><plugin filename="gz-sim-pose-publisher-system" name="gz::sim::systems::PosePublisher"><publish_model_pose>true</publish_model_pose><use_pose_vector_msg>true</use_pose_vector_msg></plugin></model>''')
    body = "\n".join(boxes)
    return f"""<?xml version="1.0"?>
<!-- GENERATED by lab-world-compiler from project {w['id']} revision {w['revision']}: ILLUSTRATIVE static scene (metres). Robots are spawned by the launch file. -->
<sdf version="1.9">
  <world name="lab">
    <physics name="4ms" type="ignored"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <scene><ambient>0.6 0.6 0.6 1</ambient></scene>
    <light type="directional" name="sun"><direction>-0.5 0.1 -0.9</direction><diffuse>0.8 0.8 0.8 1</diffuse></light>
    <model name="ground"><static>true</static><link name="link">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>{num(w['width'])} {num(w['height'])}</size></plane></geometry></collision>
      <visual name="v"><pose>{num(w['width'] / 2)} {num(w['height'] / 2)} 0 0 0 0</pose><geometry><plane><normal>0 0 1</normal><size>{num(w['width'])} {num(w['height'])}</size></plane></geometry></visual></link></model>
{body}
  </world>
</sdf>
""".encode()


def wheel_geometry(asset):
    """Drive wheels from the asset's `drive` frame box (separation = box y size, radius = box z size / 2); compiler default otherwise."""
    drive = next((s for s in asset.shapes if s.frame_id == "drive" and s.kind == "box"), None)
    if drive is None:
        return dict(DEFAULT_WHEEL), "drive geometry not in the asset: compiler default wheel separation/radius (illustrative)"
    return {"separationM": drive.dims["sizeM"][1], "radiusM": drive.dims["sizeM"][2] / 2}, None


def robot_urdf(model, robot):
    a, ns = robot.asset, robot.namespace
    wheel, _ = wheel_geometry(a)
    body = [s for s in a.shapes if s.frame_id not in ("drive",) and s.frame_id not in (a.revision.get("sensorRefs") or [])]
    chassis = next((s for s in body if s.kind == "box"), body[0])
    m = a.mass_kg
    sx, sy, sz = chassis.dims["sizeM"] if chassis.kind == "box" else (2 * chassis.dims.get("radiusM", 0.1),) * 3
    ixx, iyy, izz = m * (sy * sy + sz * sz) / 12, m * (sx * sx + sz * sz) / 12, m * (sx * sx + sy * sy) / 12
    parts = [f'<visual>{origin(s.position, s.quaternion)}<geometry>{geometry_xml(s)}</geometry></visual><collision>{origin(s.position, s.quaternion)}<geometry>{geometry_xml(s)}</geometry></collision>' for s in body]
    sensor = next((a.poses[r] for r in (a.revision.get("sensorRefs") or []) if r in a.poses), None)
    length = chassis.dims["sizeM"][0] if chassis.kind == "box" else 0.4
    speed = robot.speed_limit_mps if robot.speed_limit_mps else DEFAULT_MAX_LINEAR_MPS
    wr, ws = wheel["radiusM"], wheel["separationM"]
    wheel_inertia = f'<inertial><mass value="1"/><inertia ixx="{num((3 * wr * wr + WHEEL_WIDTH_M ** 2) / 12)}" iyy="{num(wr * wr / 2)}" izz="{num((3 * wr * wr + WHEEL_WIDTH_M ** 2) / 12)}" ixy="0" ixz="0" iyz="0"/></inertial>'
    wheels = "".join(f'''
  <link name="{name}_wheel"><visual><origin rpy="{num(math.pi / 2)} 0 0"/><geometry><cylinder radius="{num(wr)}" length="{num(WHEEL_WIDTH_M)}"/></geometry></visual>
    <collision><origin rpy="{num(math.pi / 2)} 0 0"/><geometry><cylinder radius="{num(wr)}" length="{num(WHEEL_WIDTH_M)}"/></geometry></collision>{wheel_inertia}</link>
  <joint name="{name}_wheel_joint" type="continuous"><parent link="base_link"/><child link="{name}_wheel"/><origin xyz="0 {num(side * ws / 2)} {num(wr)}" rpy="0 0 0"/><axis xyz="0 1 0"/></joint>''' for name, side in (("left", 1), ("right", -1)))
    casters = "".join(f'''
  <link name="{name}_caster"><collision><geometry><sphere radius="{num(wr)}"/></geometry></collision><visual><geometry><sphere radius="{num(wr)}"/></geometry></visual>
    <inertial><mass value="0.5"/><inertia ixx="0.001" iyy="0.001" izz="0.001" ixy="0" ixz="0" iyz="0"/></inertial></link>
  <joint name="{name}_caster_joint" type="fixed"><parent link="base_link"/><child link="{name}_caster"/><origin xyz="{num(x)} 0 {num(wr)}"/></joint>
  <gazebo reference="{name}_caster"><mu1>0.0</mu1><mu2>0.0</mu2></gazebo>''' for name, x in (("front", length / 2 - CASTER_INSET_M), ("rear", -length / 2 + CASTER_INSET_M)))
    lidar = "" if sensor is None else f'''
  <link name="lidar_link"><visual><geometry><cylinder radius="0.04" length="0.05"/></geometry></visual><inertial><mass value="0.2"/><inertia ixx="0.0002" iyy="0.0002" izz="0.0002" ixy="0" ixz="0" iyz="0"/></inertial></link>
  <joint name="lidar_joint" type="fixed"><parent link="base_link"/><child link="lidar_link"/>{origin(sensor[0], sensor[1])}</joint>
  <gazebo reference="lidar_link"><sensor name="lidar" type="gpu_lidar"><topic>/{ns}/scan</topic><gz_frame_id>lidar_link</gz_frame_id><update_rate>10</update_rate><always_on>true</always_on>
    <lidar><scan><horizontal><samples>360</samples><min_angle>-3.14159</min_angle><max_angle>3.14159</max_angle></horizontal></scan><range><min>0.12</min><max>8.0</max><resolution>0.01</resolution></range></lidar></sensor></gazebo>'''
    return f'''<?xml version="1.0"?>
<!-- GENERATED by lab-world-compiler for entity {robot.entity_id} from asset {a.revision['id']}@{a.revision['revision']} ({a.revision['contentHash'][:12]}): ILLUSTRATIVE geometry.
     The diff-drive <topic> below is the only motion input, published by Nav2 collision_monitor; the platform never publishes motor commands. -->
<robot name="mekoniq_{ns}">
  <link name="base_link">{"".join(parts)}
    <inertial>{origin(chassis.position, chassis.quaternion)}<mass value="{num(m)}"/><inertia ixx="{num(ixx)}" iyy="{num(iyy)}" izz="{num(izz)}" ixy="0" ixz="0" iyz="0"/></inertial>
  </link>{wheels}{casters}{lidar}
  <gazebo reference="base_link"><sensor name="contact" type="contact"><contact><collision>base_link_collision</collision></contact><topic>/model/{ns}/contacts</topic><always_on>true</always_on><update_rate>50</update_rate></sensor></gazebo>
  <gazebo>
    <plugin filename="gz-sim-diff-drive-system" name="gz::sim::systems::DiffDrive">
      <left_joint>left_wheel_joint</left_joint><right_joint>right_wheel_joint</right_joint><wheel_separation>{num(ws)}</wheel_separation><wheel_radius>{num(wr)}</wheel_radius>
      <topic>/{ns}/cmd_vel</topic><odom_topic>/{ns}/odom</odom_topic><tf_topic>/{ns}/tf</tf_topic><frame_id>odom</frame_id><child_frame_id>base_link</child_frame_id><odom_publish_frequency>30</odom_publish_frequency>
      <max_linear_velocity>{num(speed)}</max_linear_velocity><max_angular_velocity>1.0</max_angular_velocity><max_linear_acceleration>1.0</max_linear_acceleration><max_angular_acceleration>2.0</max_angular_acceleration>
    </plugin>
    <plugin filename="gz-sim-pose-publisher-system" name="gz::sim::systems::PosePublisher"><publish_model_pose>true</publish_model_pose><use_pose_vector_msg>true</use_pose_vector_msg></plugin>
    <plugin filename="gz-sim-joint-state-publisher-system" name="gz::sim::systems::JointStatePublisher"><topic>/{ns}/joint_states</topic></plugin>
  </gazebo>
</robot>
'''.encode()


def nav2_overlay(model, robot, bindings, map_id, map_revision):
    fp = robot.asset.footprint
    spawn = bindings[robot.parking_id]
    lines = [f"namespace: {robot.namespace}", "use_sim_time: true", f"map_id: {map_id}", f'map_revision: "{map_revision}"', "map_yaml: map.yaml",
             f"robot_radius: {num(robot.asset.radius_m)}",
             f'footprint: "[[{num(fp[2])},{num(fp[3])}],[{num(fp[2])},{num(fp[1])}],[{num(fp[0])},{num(fp[1])}],[{num(fp[0])},{num(fp[3])}]]"',
             f"initial_pose_x: {num(spawn['x'])}", f"initial_pose_y: {num(spawn['y'])}", f"initial_pose_yaw: {num(spawn['yaw'])}",
             f"max_linear_mps: {num(robot.speed_limit_mps or DEFAULT_MAX_LINEAR_MPS)}"]
    return ("\n".join(lines) + "\n").encode()


def compile_world(project_json, asset_revisions, output_dir, *, run_root=None, map_id="lab-world", fixture_height_m=None, scenario=None):
    """`scenario`: a validated SIL scenario (actors.scenario.load_scenario); its actors/blockers/zones enter the world and the bundle identity."""
    from bridge.tray_observer import validate_beverage_fixture
    beverage = validate_beverage_fixture(scenario["beverage"]) if scenario and "beverage" in scenario else None
    model = WorldModel.validate(project_json, asset_revisions, **({} if fixture_height_m is None else {"fixture_height_m": fixture_height_m}))
    model.assert_target_clearance()
    actors, blockers = (actor_schedules(scenario), BlockerSchedule(scenario["blockers"])) if scenario else ([], None)
    taken = {p["id"] for p in model.world["points"]} | {o["id"] for o in model.world["obstacles"]} | {e["id"] for e in project_json["entities"]}
    for extra in [a.actor_id for a in actors] + [b["id"] for b in (blockers.blockers if blockers else [])] + [z["id"] for z in (scenario or {}).get("zones", [])]:
        if extra in taken:
            raise CompileError("ID_DUPLICATE", extra)
        taken.add(extra)
    out = resolve_output(output_dir, run_root)
    w = model.world
    map_revision = str(w["revision"])
    world_hash = canonical_hash(w)
    input_hash = canonical_hash({"project": project_json, "assets": asset_revisions, **({"scenario": scenario} if scenario else {})})
    bindings = model.bindings()
    for b in bindings.values():
        b.update({"frame": "map", "mapId": map_id, "mapRevision": map_revision})
    rects = model.walls + [(o["x"], o["y"], o["width"], o["height"]) for o in w["obstacles"]]
    pgm = occupancy_pgm(rects, w["width"], w["height"])
    identity, identity_bytes = map_identity(map_id, map_revision, world_hash, pgm, w["width"], w["height"])
    files = {"world.sdf": world_sdf(model, actors, blockers, beverage=beverage), "map.pgm": pgm, "map.yaml": map_yaml().encode(), "map.identity.json": identity_bytes,
             "bindings.json": (json.dumps({"frame": "map", "mapId": map_id, "mapRevision": map_revision, "bindings": bindings}, indent=2, sort_keys=True) + "\n").encode()}
    assumptions = list(model.assumptions)
    robots, entities = [], []
    for r in model.robots:
        _, note = wheel_geometry(r.asset)
        if note and note not in assumptions:
            assumptions.append(note)
        files[f"robot-{r.entity_id}.urdf"] = robot_urdf(model, r)
        files[f"nav2-{r.entity_id}.yaml"] = nav2_overlay(model, r, bindings, map_id, map_revision)
        spawn = {"x": bindings[r.parking_id]["x"], "y": bindings[r.parking_id]["y"], "yaw": bindings[r.parking_id]["yaw"]}
        fp = r.asset.footprint
        robots.append({"entityId": r.entity_id, "namespace": r.namespace, "assetRef": r.asset.ref, "radiusM": r.asset.radius_m,
                       "footprint": {"min": [fp[0], fp[1]], "max": [fp[2], fp[3]]}, "mass": {"kg": r.asset.mass_kg, "provenance": r.asset.mass_provenance or "unknown"},
                       "parkingId": r.parking_id, "spawn": spawn, "maxLinearMps": r.speed_limit_mps or DEFAULT_MAX_LINEAR_MPS})
        entities.append({"entityId": r.entity_id, "kind": "amr", "assetRef": r.asset.ref, "gazeboModel": r.namespace, "namespace": r.namespace,
                         "baseFrame": "base_link", "spawn": spawn,
                         "telemetry": {"pose": f"/model/{r.namespace}/pose", "odom": f"/{r.namespace}/odom", "scan": f"/{r.namespace}/scan", "contacts": f"/model/{r.namespace}/contacts", "joints": f"/{r.namespace}/joint_states"},
                         "jointAuthority": [{"joint": "left_wheel_joint", "controller": "gz_diff_drive"}, {"joint": "right_wheel_joint", "controller": "gz_diff_drive"}]})
    assumptions.append(f"max linear velocity {DEFAULT_MAX_LINEAR_MPS} m/s unless the entity declares speedLimitMps (illustrative)")
    fixture_ref = model.fixture_asset.ref if model.fixture_asset else None
    scene = {"frame": "world", "units": "m", "zUp": True, "entities": entities,
             "fixtures": [{"obstacleId": o["id"], "gazeboModel": f"fixture_{o['id']}", "assetRef": fixture_ref, "heightM": model.fixture_height_m} for o in w["obstacles"]],
             "walls": [{"gazeboModel": f"wall_{i}", "rect": list(rect)} for i, rect in enumerate(model.walls)],
             "actors": [{"id": a.actor_id, "kind": "pedestrian", "gazeboModel": a.model, "heightM": a.height_m, "radiusM": a.radius_m, "provenance": a.provenance,
                         "trajectory": {"waypoints": [list(p) for p in a.trajectory.waypoints], "speedMps": a.trajectory.speed_mps, "startTick": a.trajectory.start_tick, "dwellTicks": a.dwell_ticks, "loop": a.trajectory.loop},
                         "telemetry": {"pose": f"/model/{a.model}/pose", "contacts": f"/model/{a.model}/contacts"}, "velocity": f"/model/{a.model}/cmd_vel"} for a in actors],
             "blockers": blockers.models() if blockers else [], "zones": list((scenario or {}).get("zones", []))}
    if beverage:
        scene["beverage"] = beverage
    files["scene-index.json"] = (json.dumps(scene, indent=2, sort_keys=True) + "\n").encode()
    r9 = lambda v: round(v, 9)  # stable decimal bounds: no binary-float artefacts in the manifest identity
    obstacle_bounds = ({"min": [r9(min(o["x"] for o in w["obstacles"])), r9(min(o["y"] for o in w["obstacles"])), 0],
                        "max": [r9(max(o["x"] + o["width"] for o in w["obstacles"])), r9(max(o["y"] + o["height"] for o in w["obstacles"])), model.fixture_height_m]}
                       if w["obstacles"] else None)
    refs = [{"id": a["id"], "revision": a["revision"], "contentHash": a["contentHash"]} for a in model.assets]
    manifest = {"schemaVersion": 1, "frame": "world", "units": "m", "yaw": "rad", "zUp": True,
                "project": {"id": project_json.get("id"), "revision": project_json.get("revision")},
                "scenario": {"id": scenario["id"], "revision": scenario["revision"], "scenarioId": scenario["scenarioId"]} if scenario else None,
                "world": {"id": w["id"], "revision": w["revision"], "hash": world_hash, "widthM": w["width"], "heightM": w["height"]},
                "map": {"mapId": map_id, "mapRevision": map_revision, "resolutionM": RESOLUTION_M, "origin": [0, 0, 0], "pgmSha256": identity["pgmSha256"], "inflation": "none"},
                "visualAssetRevisionRefs": refs, "collisionAssetRevisionRefs": refs,
                "visualBlobs": [{"assetId": a["id"], **(a.get("visual") or {})} for a in model.assets if a.get("visual")],
                "collisionBlobs": [{"assetId": a["id"], **(a.get("collision") or {})} for a in model.assets if a.get("collision")],
                "collisionBounds": obstacle_bounds, "worldBounds": {"min": [0, 0, 0], "max": [w["width"], w["height"], WALL_HEIGHT_M]},
                "robots": robots, "fixtureHeightM": model.fixture_height_m, "assumptions": assumptions, "warnings": [],
                "backendCompatibility": {"gazebo_nav2": {"compatible": True, "reasons": [], "dynamicsProvenance": sorted({r["mass"]["provenance"] for r in robots})}}}
    return write_hashed_bundle(out, input_hash, manifest, files)
