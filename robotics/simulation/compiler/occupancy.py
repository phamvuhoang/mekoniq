"""Raw occupancy for Nav2 (no inflation: footprint + clearance policy belong to the Nav2 costmap, never to the map). Map frame == world frame, metres, origin (0,0)."""
import hashlib
import json

from worlds.generate_restaurant import rasterize

RESOLUTION_M = 0.05


def occupancy_pgm(rects, width, height, resolution=RESOLUTION_M):
    """rects: (x, y, w, h) static collision rectangles in metres (walls + extruded fixtures)."""
    boxes = [(x + w / 2, y + h / 2, w, h) for x, y, w, h in rects]
    return rasterize(boxes, width, height, resolution, b"GENERATED by lab-world-compiler (illustrative, raw occupancy)")


def map_yaml(resolution=RESOLUTION_M):
    return f"image: map.pgm\nmode: trinary\nresolution: {resolution}\norigin: [0.0, 0.0, 0.0]\nnegate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n"


def map_identity(map_id, map_revision, world_hash, pgm, width, height, resolution=RESOLUTION_M):
    identity = {"mapId": map_id, "mapRevision": map_revision, "frame": "map", "origin": [0, 0, 0], "resolution": resolution,
                "widthCells": round(width / resolution), "heightCells": round(height / resolution), "pgmSha256": hashlib.sha256(pgm).hexdigest(),
                "worldHash": world_hash, "inflation": "none", "illustrative": True}
    return identity, (json.dumps(identity, indent=2, sort_keys=True) + "\n").encode()
