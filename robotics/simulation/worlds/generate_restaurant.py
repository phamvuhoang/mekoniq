#!/usr/bin/env python3
"""Single source for the restaurant layout: writes restaurant.sdf (Gazebo Harmonic) and the matching Nav2 occupancy map. Stdlib only.
`python3 generate_restaurant.py [out_world_dir] [out_map_dir]`. A unit test fails if the committed files drift from this layout.
Geometry is ILLUSTRATIVE simulation data (metres); it says nothing about any real venue or robot. Map frame == world frame."""
import json
import sys
from pathlib import Path

W, H, RES = 12.0, 8.0, 0.05
# name: (cx, cy, size_x, size_y, height) -- static boxes; they are also the occupied cells of the map
BOXES = {
    "wall_south": (6.0, 0.1, 12.0, 0.2, 2.0), "wall_north": (6.0, 7.9, 12.0, 0.2, 2.0),
    "wall_west": (0.1, 4.0, 0.2, 8.0, 2.0), "wall_east": (11.9, 4.0, 0.2, 8.0, 2.0),
    "kitchen_partition_south": (3.05, 1.75, 0.3, 3.1, 2.0), "kitchen_partition_north": (3.05, 6.25, 0.3, 3.1, 2.0),
    "corridor_wall_south": (4.0, 3.4, 1.6, 0.2, 2.0), "corridor_wall_north": (4.0, 4.6, 1.6, 0.2, 2.0),  # 1.0 m wide, 1.6 m long
    "kitchen_counter": (1.0, 6.6, 1.8, 0.6, 0.9),
    "table_1": (7.0, 2.0, 0.8, 0.8, 0.75), "table_2": (7.0, 6.0, 0.8, 0.8, 0.75), "table_3": (10.0, 2.0, 0.8, 0.8, 0.75), "table_4": (10.0, 6.0, 0.8, 0.8, 0.75),
}
WAYPOINTS = {  # name: (x, y, yaw rad)
    "kitchen-pickup": (1.5, 4.0, 0.0), "table-1": (7.0, 3.1, -1.5708), "table-2": (7.0, 4.9, 1.5708),
    "table-3": (10.0, 3.1, -1.5708), "table-4": (10.0, 4.9, 1.5708), "dining-handoff": (5.6, 4.0, 0.0),
}
SPAWN = WAYPOINTS["kitchen-pickup"]
WALKER = (8.5, 7.0)   # moving obstacle start; driven by gz topic /model/walker/cmd_vel
BLOCKER = (9.0, 0.6)  # parked off-path; moved with the set_pose service to block a route
IDENTITY = {"mapId": "map-a", "mapRevision": "r1", "illustrative": True}


def box_sdf(name, cx, cy, sx, sy, h):
    return f"""    <model name="{name}"><static>true</static><pose>{cx} {cy} {h / 2} 0 0 0</pose><link name="link">
      <collision name="c"><geometry><box><size>{sx} {sy} {h}</size></box></geometry></collision>
      <visual name="v"><geometry><box><size>{sx} {sy} {h}</size></box></geometry></visual></link></model>"""


def mover_sdf(name, cx, cy, size, h, color):
    """Kinematic box mover (velocity-controlled, pose published). `size` is a side length or an (sx, sy) footprint."""
    sx, sy = size if isinstance(size, (tuple, list)) else (size, size)
    return f"""    <model name="{name}"><pose>{cx} {cy} {h / 2 + 0.02} 0 0 0</pose><link name="link"><gravity>false</gravity>
      <inertial><mass>20</mass><inertia><ixx>1</ixx><iyy>1</iyy><izz>1</izz></inertia></inertial>
      <collision name="c"><geometry><box><size>{sx} {sy} {h}</size></box></geometry></collision>
      <visual name="v"><geometry><box><size>{sx} {sy} {h}</size></box></geometry><material><ambient>{color}</ambient><diffuse>{color}</diffuse></material></visual></link>
      <plugin filename="gz-sim-velocity-control-system" name="gz::sim::systems::VelocityControl"/>
      <plugin filename="gz-sim-pose-publisher-system" name="gz::sim::systems::PosePublisher">
        <publish_model_pose>true</publish_model_pose><use_pose_vector_msg>true</use_pose_vector_msg><static_publisher>false</static_publisher>
      </plugin>
    </model>"""


def world_sdf():
    boxes = "\n".join(box_sdf(n, *b) for n, b in BOXES.items())
    return f"""<?xml version="1.0"?>
<!-- GENERATED by generate_restaurant.py - do not edit. ILLUSTRATIVE restaurant: kitchen (x<3), 1.0 m x 1.6 m corridor, dining room, 4 tables,
     a walking obstacle (/model/walker/cmd_vel) and a parked blocker (moved by the /world/restaurant/set_pose service). -->
<sdf version="1.9">
  <world name="restaurant">
    <physics name="1ms" type="ignored"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <scene><ambient>0.6 0.6 0.6 1</ambient></scene>
    <light type="directional" name="sun"><direction>-0.5 0.1 -0.9</direction><diffuse>0.8 0.8 0.8 1</diffuse></light>
    <model name="ground"><static>true</static><link name="link">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>{W} {H}</size></plane></geometry></collision>
      <visual name="v"><pose>{W / 2} {H / 2} 0 0 0 0</pose><geometry><plane><normal>0 0 1</normal><size>{W} {H}</size></plane></geometry></visual></link></model>
{boxes}
{mover_sdf("walker", WALKER[0], WALKER[1], 0.4, 1.0, "0.9 0.3 0.1 1")}
{mover_sdf("blocker", BLOCKER[0], BLOCKER[1], 0.8, 1.0, "0.6 0.1 0.6 1")}
  </world>
</sdf>
"""


def rasterize(boxes, w, h, res, comment):
    """Raw occupancy (no inflation): PGM bytes, 254 free / 0 occupied, row 0 is the top (max y). boxes: (cx, cy, size_x, size_y) in metres."""
    nx, ny = round(w / res), round(h / res)
    grid = [[254] * nx for _ in range(ny)]
    for cx, cy, sx, sy in boxes:
        for r in range(ny):
            y = (ny - 1 - r + 0.5) * res
            if abs(y - cy) <= sy / 2:
                for c in range(nx):
                    if abs((c + 0.5) * res - cx) <= sx / 2:
                        grid[r][c] = 0
    return b"P5\n# %s\n%d %d\n255\n" % (comment, nx, ny) + b"".join(bytes(row) for row in grid)


def map_pgm():
    return rasterize([box[:4] for box in BOXES.values()], W, H, RES, b"GENERATED by generate_restaurant.py (illustrative)")


def map_yaml():
    return f"image: restaurant_sim.pgm\nmode: trinary\nresolution: {RES}\norigin: [0.0, 0.0, 0.0]\nnegate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n"


def outputs():
    return {"world": ("restaurant.sdf", world_sdf().encode()), "pgm": ("restaurant_sim.pgm", map_pgm()), "yaml": ("restaurant_sim.yaml", map_yaml().encode()),
            "identity": ("restaurant_sim.identity.json", (json.dumps({**IDENTITY, "waypoints": WAYPOINTS}, indent=2) + "\n").encode())}


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    world_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else here
    map_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else here.parent.parent / "navigation" / "maps"
    for key, (name, data) in outputs().items():
        (world_dir if key == "world" else map_dir).joinpath(name).write_bytes(data)
