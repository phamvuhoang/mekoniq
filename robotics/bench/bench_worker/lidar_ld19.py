_BODY = struct.Struct("<BBHH" + "HB" * POINTS + "HHB")


def crc8(data: bytes) -> int:
    c = 0
    for b in data:
        c = _CRC[c ^ b]
    return c


def parse(buf: bytearray):
    """Consumes `buf` in place: every complete frame whose CRC is right becomes a dict, everything else before it is dropped (and counted), an incomplete
    tail stays for the next call. A CRC failure drops one byte and looks for the next header, so a frame whose data holds 0x54 0x2C is not mistaken for two.
    Returns ([{speedDegS, startDeg, endDeg, sensorMs, points: [(mm, intensity)] x 12}], bytes dropped). Never raises."""
    frames, dropped, i = [], 0, 0
    while True:
        j = buf.find(b"\x54\x2c", i)
        if j < 0:   # no header: all junk, except a final 0x54 that may be the first half of one
            keep = 1 if buf.endswith(b"\x54") and len(buf) > i else 0
            dropped += len(buf) - i - keep
            del buf[:len(buf) - keep]
            return frames, dropped
        dropped += j - i
        if len(buf) - j < FRAME_LEN:
            del buf[:j]
            return frames, dropped
        if crc8(buf[j:j + FRAME_LEN - 1]) != buf[j + FRAME_LEN - 1]:
            dropped, i = dropped + 1, j + 1
            continue
        v = _BODY.unpack_from(buf, j)
        frames.append({"speedDegS": v[2], "startDeg": v[3] / 100, "endDeg": v[4 + 2 * POINTS] / 100, "sensorMs": v[5 + 2 * POINTS],
                       "points": [(v[4 + 2 * k], v[5 + 2 * k]) for k in range(POINTS)]})
        i = j + FRAME_LEN
