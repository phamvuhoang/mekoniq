import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
export function renderTokens(t) {
 if(t.schemaVersion!==1 || !/^\d+\.\d+\.\d+$/.test(t.brandVersion))throw Error('Invalid token schema/version');
 const all={...t.primitives,...t.semantic};
 function resolve(key,seen=new Set()) {if(seen.has(key))throw Error('Cyclic alias');if(!(key in all))throw Error('Unknown alias '+key);seen.add(key);const value=all[key];for(const m of value.matchAll(/var\(\s*(--[\w-]+)\s*\)/g))resolve(m[1],new Set(seen));}
 for(const key of Object.keys(all)){if(!/^--(?:mq|mekoniq)-[a-z0-9-]+$/.test(key)||/[;{}\n]/.test(all[key]))throw Error('Unsafe token');resolve(key);}
 return '/* MEKONIQ '+t.brandVersion+' — generated by build-brand.mjs */\n:root {\n'+Object.keys(all).sort().map(k=>'  '+k+': '+all[k]+';').join('\n')+'\n}\n';
}
if(process.argv[1]===fileURLToPath(import.meta.url)){const dir=new URL('../packages/ui/brand/',import.meta.url);writeFileSync(new URL('tokens.css',dir),renderTokens(JSON.parse(readFileSync(new URL('tokens.json',dir),'utf8'))));}
